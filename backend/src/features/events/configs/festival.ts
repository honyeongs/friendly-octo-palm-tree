import { EventType, type EventDefinition, type RewardSpec } from '../EventTypes.js';
export function festival(
  id: string,
  name: string,
  startAt: string,
  endAt: string,
  theme: string,
  currencyName: string,
  eventType = EventType.SEASONAL,
): EventDefinition {
  const currencyId = `${id}_currency`;
  const currency = (amount: number): RewardSpec => ({
    rewardType: 'EVENT_CURRENCY',
    rewardId: currencyId,
    rewardAmount: amount,
  });
  return {
    id,
    name,
    description: '출석과 교역 미션으로 기념품을 모으세요.',
    eventType,
    startAt,
    endAt,
    active: true,
    bannerImageUrl: '/cosmetics/banner.svg',
    theme,
    createdAt: '2026-09-12T00:00:00+09:00',
    currency: { id: currencyId, eventId: id, name: currencyName, iconUrl: '/cosmetics/emote.svg' },
    cosmetics: [
      ...(['dice', 'frame', 'emote'] as const).map((kind, i) => ({
        id: `${id}_${kind}_shop`,
        eventId: id,
        cosmeticType: (['DICE_SKIN', 'PROFILE_FRAME', 'EMOTE'] as const)[i]!,
        cosmeticId: `${id}_${kind}`,
        acquisitionMethod: 'EVENT_SHOP' as const,
        availableFrom: startAt,
        availableUntil: endAt,
      })),
      {
        id: `${id}_attendance_dice`,
        eventId: id,
        cosmeticType: 'DICE_SKIN',
        cosmeticId: `${id}_dice`,
        acquisitionMethod: 'EVENT_ATTENDANCE',
        availableFrom: startAt,
        availableUntil: endAt,
      },
    ],
    shop: (['dice', 'frame', 'emote'] as const).map((kind, i) => ({
      id: `${id}_shop_${kind}`,
      eventId: id,
      itemType: (['DICE_SKIN', 'PROFILE_FRAME', 'EMOTE'] as const)[i]!,
      itemId: `${id}_${kind}`,
      price: [500, 300, 100][i]!,
      currencyId,
      purchaseLimit: 1,
      availableFrom: startAt,
      availableUntil: endAt,
    })),
    missions: [
      {
        id: `${id}_play1`,
        eventId: id,
        title: '첫 거래',
        description: '게임 1회 완료',
        targetType: 'PLAY_GAME',
        targetAmount: 1,
        ...currency(20),
      },
      {
        id: `${id}_play3`,
        eventId: id,
        title: '꾸준한 항해',
        description: '게임 3회 완료',
        targetType: 'PLAY_GAME',
        targetAmount: 3,
        ...currency(50),
      },
      {
        id: `${id}_win`,
        eventId: id,
        title: '승리의 별길',
        description: '1승 달성',
        targetType: 'WIN_GAME',
        targetAmount: 1,
        ...currency(50),
      },
      {
        id: `${id}_cities`,
        eventId: id,
        title: '도시 수집가',
        description: '도시 10개 구매',
        targetType: 'BUY_CITY',
        targetAmount: 10,
        ...currency(100),
      },
      {
        id: `${id}_landmarks`,
        eventId: id,
        title: '랜드마크 건축가',
        description: '랜드마크 3개 건설',
        targetType: 'BUILD_LANDMARK',
        targetAmount: 3,
        ...currency(100),
      },
    ],
    attendance: [
      currency(50),
      { rewardType: 'COIN', rewardId: 'coin', rewardAmount: 100 },
      currency(100),
      { rewardType: 'BOX', rewardId: 'festival_box', rewardAmount: 1 },
      currency(150),
      { rewardType: 'COIN', rewardId: 'coin', rewardAmount: 300 },
      { rewardType: 'COSMETIC', rewardId: `${id}_dice`, rewardAmount: 1 },
    ],
    rewards: [{ id: `${id}_welcome`, title: '축제 환영 선물', ...currency(100) }],
  };
}
