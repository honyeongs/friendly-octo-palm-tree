"""Generate runtime pins, a license inventory, CycloneDX SBOM and notices."""

import hashlib
import importlib.metadata as metadata
import json
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
ROOTS = ['fastapi', 'uvicorn', 'python-dotenv', 'dpkt', 'authlib', 'httpx', 'stripe', 'psycopg[binary]', 'cryptography']


def inventory():
    packages, pending, seen = {}, [Requirement(item) for item in ROOTS], set()
    while pending:
        requirement = pending.pop()
        key = (canonicalize_name(requirement.name), tuple(sorted(requirement.extras)))
        if key in seen:
            continue
        seen.add(key)
        dist = metadata.distribution(requirement.name)
        packages[key[0]] = dist
        for raw in dist.requires or []:
            child = Requirement(raw)
            if child.marker is None or any(child.marker.evaluate({'extra': extra}) for extra in (requirement.extras or {''})):
                pending.append(child)
    output, notices = [], ROOT / 'third_party'
    notices.mkdir(exist_ok=True)
    for name, dist in sorted(packages.items()):
        license_files = []
        destination = notices / name
        destination.mkdir(exist_ok=True)
        for item in dist.files or []:
            # Package license files are copied without rewriting their terms or copyright.
            if ('dist-info' in str(item) and ('license' in item.name.lower() or 'copying' in item.name.lower() or 'notice' in item.name.lower())):
                data = dist.locate_file(item).read_bytes()
                filename = str(item).split('.dist-info/')[-1].replace('/', '__').replace('\\', '__')
                target = destination / filename
                target.write_bytes(data)
                license_files.append({'path': target.relative_to(ROOT).as_posix(), 'sha256': hashlib.sha256(data).hexdigest()})
        output.append({'name': name, 'version': dist.version, 'license_expression': dist.metadata.get('License-Expression'),
                       'license_metadata': dist.metadata.get('License'),
                       'classifiers': [value for value in dist.metadata.get_all('Classifier', []) if value.startswith('License ::')],
                       'notices': license_files})
    (ROOT / 'requirements-runtime.lock').write_text('# Generated by scripts/supply_chain.py; audit and regenerate for releases.\n' +
        ''.join(f"{item['name']}=={item['version']}\n" for item in output), encoding='utf-8')
    (ROOT / 'docs' / 'DEPENDENCIES.json').write_text(json.dumps({'scope': 'Runtime SaaS + optional PCAP packages; OS images/dev tools excluded', 'packages': output}, indent=2), encoding='utf-8')
    components = [{'type': 'library', 'name': item['name'], 'version': item['version'],
                   'purl': f"pkg:pypi/{item['name']}@{item['version']}",
                   **({'licenses': [{'expression': item['license_expression']}]} if item['license_expression'] else {})} for item in output]
    (ROOT / 'docs' / 'SBOM.cdx.json').write_text(json.dumps({'bomFormat': 'CycloneDX', 'specVersion': '1.6', 'version': 1, 'components': components}, indent=2), encoding='utf-8')
    print(json.dumps({'runtime_packages': len(output), 'missing_notices': [item['name'] for item in output if not item['notices']]}))


if __name__ == '__main__':
    inventory()
